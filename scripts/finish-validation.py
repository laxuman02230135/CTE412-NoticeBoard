"""Recheck baseline, exercise README rebuild, and clean up only the lab cluster."""
import importlib.util
import json
import pathlib
import subprocess
import time

root=pathlib.Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('lab',root/'scripts/repeat-lab.py')
lab=importlib.util.module_from_spec(spec); spec.loader.exec_module(lab)
K=lab.K
assert len(json.loads((lab.E/'t9-results.json').read_text()))==7
print('Checking a full stable minute with the same monitor',flush=True)
start=lab.stamp(); time.sleep(61)
log=lab.run(K+['logs','monitor','--since-time='+start])
lines=log.splitlines(); assert len(lines)>=120 and ' FAIL ' not in log
from datetime import datetime
span=(datetime.fromisoformat(lines[-1].split()[0].replace('Z','+00:00'))-datetime.fromisoformat(lines[0].split()[0].replace('Z','+00:00'))).total_seconds()
assert span>=60, span
lab.save('t4-at-rest-log.txt',log)
lab.save('t4-at-rest-first10.txt','\n'.join(lines[:10])+'\n')
lab.save('t4-at-rest-summary.txt',lab.run(['docker','run','--rm','--mount',f'type=bind,source={root},target=/lab,readonly','notice-board:02230135-1.0.0','sh','/lab/scripts/summarise.sh','/lab/evidence/t4-at-rest-log.txt']))
lab.save('t4-baseline-recheck.txt',f'Student ID: 02230135\nRechecked after Task 8 on stable green 1.1.0 using the original continuous monitor.\nObserved duration: {span:.3f} seconds\nInitial new-session capture had fewer than sixty seconds of emitted samples; this replaces it.\n')
lab.save('t9-monitor-full.log',lab.run(K+['logs','monitor']))
for task in ['t6','t8']:
    lab.save(task+'-events.txt',(lab.E/(task+'-monitor-events.txt')).read_text())
print('Removing namespace workloads for the README rebuild rehearsal',flush=True)
lab.run(K+['get','deployment,pod,service,configmap,quota,limitrange'],'t9-before-rebuild.txt')
removal=lab.run(K+['delete','-f',root/'manifests/bluegreen','--ignore-not-found=true','--wait=true'])
removal+=lab.run(K+['delete','-f',root/'manifests/base/04-monitor-pod.yaml','--ignore-not-found=true','--wait=true'])
removal+=lab.run(K+['delete','-f',root/'manifests/base/03-monitor-code.yaml','--ignore-not-found=true'])
# Remove residual namespace objects, including Events; defaults may be regenerated by Kubernetes.
removal+=lab.run(K+['delete','replicasets,pods,services,configmaps,secrets,serviceaccounts,events','--all','--ignore-not-found=true','--wait=false'])
lab.save('t9-removal.txt','Student ID: 02230135\n'+removal)
time.sleep(2)
for kind in ['deployment','pod','service']:
    assert not lab.obj(kind)['items'], f'Residual {kind}'
assert lab.obj('resourcequota','notice-board-quota')
assert lab.obj('limitrange','notice-board-defaults')
lab.run(K+['get','deployments,replicasets,pods,services,configmaps,secrets,serviceaccounts,resourcequota,limitrange'],'t9-after-removal.txt')
print('Executing the exact README rebuild script',flush=True)
lab.run(['powershell','-NoProfile','-ExecutionPolicy','Bypass','-File','scripts/rebuild-final.ps1'],'t9-rebuild.txt')
assert lab.host('/version')['version']=='1.1.0'
assert lab.host('/notices')['pinnedFirst'] is True
for name in ['notice-board-blue','notice-board-green']:
    assert lab.obj('deployment',name)['status']['availableReplicas']==3
for name in ['notice-board','notice-board-ext']:
    assert lab.obj('service',name)['spec']['selector']['slot']=='green'
assert lab.obj('service','notice-board-preview')['spec']['selector']['slot']=='green'
for path in [*root.glob('manifests/base/*.yaml'),*root.glob('manifests/bluegreen/*.yaml')]:
    lab.run(K+['apply','--dry-run=server','--validate=strict','-f',path])
lab.run(K+['get','deployments,pods,services,configmaps,resourcequota,limitrange'],'t9-rebuilt-final-state.txt')
lab.save('t9-rebuilt-notices.txt',json.dumps(lab.host('/notices'),indent=2)+'\n')
print('Rebuild verified; deleting only cte412-02230135',flush=True)
cleanup='Student ID: 02230135\n'+lab.run(['kubectl','config','set-context',lab.CTX,'--namespace=default'])
cleanup+=lab.run(['kind','delete','cluster','--name',lab.NAME])
remaining=lab.run(['kind','get','clusters']); assert lab.NAME not in remaining.splitlines()
cleanup+='Remaining clusters:\n'+remaining
lab.save('t9-cluster-deleted.txt',cleanup)
print('Rebuild and cleanup passed.',flush=True)
